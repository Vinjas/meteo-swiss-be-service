export function mapMeteoSwissIcon(code: unknown, isDay = true): string {
  const value = Number(code);
  if (!Number.isFinite(value)) return isDay ? '01d' : '01n';

  const icon = METEOSWISS_ICON_MAP[value];
  if (!icon) return isDay ? '03d' : '02n';
  return typeof icon === 'string' ? icon : isDay ? icon.day : icon.night;
}
